"""Generate lex.l's patterns for the UTF-8 characters names may hold.

Names may hold any UTF-8 character except those the lexer's rules use
in operators, so that a⫽b and x² lex as they read. Flex matches bytes,
so the patterns list the well-formed UTF-8 sequences with their byte
ranges split around those characters. This finds the characters in the
quoted patterns of lex.l's rules and rewrites the definitions between
the markers in lex.l, or with --check, reports whether they are current.
"""

import argparse
import re
import sys

BEGIN = '/* Generated by mkutf8names.py: names\' UTF-8 characters */\n'
END = '/* End of mkutf8names.py output */\n'
WIDTH = 100


def operator_chars(text):
    """
    The non-ASCII characters in the quoted patterns of the rules, each
    with the tokens of the rules using it
    """
    rules = text.split('\n%%\n')[1]
    chars = {}
    for line in rules.splitlines():
        m = re.match(r'"((?:[^"\\]|\\.)*)"(.*)', line)
        if not m:
            continue
        token = re.search(r'\b[A-Z][A-Z0-9_]+\b', m.group(2))
        for c in m.group(1):
            if ord(c) > 0x7f:
                tokens = chars.setdefault(c, [])
                if token and token.group(0) not in tokens:
                    tokens.append(token.group(0))
    return chars


def ranges(vals):
    out = []
    for v in sorted(vals):
        if out and out[-1][1] == v - 1:
            out[-1][1] = v
        else:
            out.append([v, v])
    return out


def byte(b):
    return '\\x%02x' % b


def byte_class(vals):
    return '[' + ''.join(byte(a) if a == b else byte(a) + '-' + byte(b)
                         for a, b in ranges(vals)) + ']'


CONT = set(range(0x80, 0xc0))


def sequences(length, excluded):
    """
    Alternatives matching the byte sequences of length but those
    excluded, (bytes, character) pairs, each with the characters it
    splits around
    """
    if length == 1:
        return [(byte_class(CONT - {s[0] for s, c in excluded}), {c for s, c in excluded})]
    alts = []
    split = {s[0] for s, c in excluded}
    plain = CONT - split
    if plain:
        alts.append((byte_class(plain) + '{U8CONT}' * (length - 1), set()))
    for b in sorted(split):
        rest = [(s[1:], c) for s, c in excluded if s[0] == b]
        for alt, chars in sequences(length - 1, rest):
            alts.append((byte(b) + alt, chars))
    return alts


def describe(chars, tokens):
    """Comment lines naming each character, its bytes, and its tokens"""
    lines = ['/*\n']
    for c in sorted(chars):
        lines.append(' * %s %s: %s\n' % (c, ''.join(byte(b) for b in c.encode()),
                                         ' '.join(tokens[c])))
    lines.append(' */\n')
    return ''.join(lines)


def definitions(tokens):
    excluded = [(c.encode(), c) for c in tokens]
    defs = [('U8CONT', '[\\x80-\\xbf]', set())]
    # The U8LETTER definitions follow all the others
    letter_defs = []
    letters = []
    for length, first, last in ((2, 0xc2, 0xdf), (3, 0xe0, 0xef), (4, 0xf0, 0xf4)):
        letter = []
        plain = []
        for lead in range(first, last + 1):
            mine = [(s[1:], c) for s, c in excluded if len(s) == length and s[0] == lead]
            if not mine:
                plain.append(lead)
                continue
            # Split the lead's alternatives over definitions short enough to read
            alts = sequences(length - 1, mine)
            n = 0
            while alts:
                name = 'U8%02X_%s' % (lead, chr(ord('A') + n))

                def width(k):
                    return (len('%-12s' % name) + len(byte(lead)) + 2
                            + len('|'.join(a for a, c in alts[:k])))
                take = 1
                while take < len(alts) and width(take + 1) <= WIDTH:
                    take += 1
                defs.append((name, byte(lead) + '(' + '|'.join(a for a, c in alts[:take]) + ')',
                             set().union(*(c for a, c in alts[:take]))))
                letter.append('{%s}' % name)
                alts = alts[take:]
                n += 1
        if plain:
            letter.append(byte_class(plain) + '{U8CONT}' * (length - 1))
        letter_defs.append(('U8LETTER_%d' % length, '|'.join(letter), set()))
        letters.append('{U8LETTER_%d}' % length)
    letter_defs.append(('U8LETTER', '|'.join(letters), set()))
    defs += letter_defs
    out = []
    for name, pattern, chars in defs:
        if chars:
            out.append(describe(chars, tokens))
        out.append('%-12s%s\n' % (name, pattern))
    return ''.join(out)


def generate(text):
    tokens = operator_chars(text)
    lines = ['/*\n',
             ' * Names may hold any UTF-8 character but those operators use, so\n',
             ' * that a name next to an operator lexes as it reads. Above each\n',
             ' * definition splitting byte ranges around some of those characters\n',
             ' * are the characters, their bytes, and the tokens of the rules using\n',
             ' * them. Regenerate these with ninja utf8-names after changing those\n',
             ' * operators\n',
             ' */\n']
    block = BEGIN + ''.join(lines) + definitions(tokens) + END
    start = text.find(BEGIN)
    end = text.find(END)
    if start < 0 or end < start:
        sys.exit('lex.l: missing the mkutf8names.py markers')
    return text[:start] + block + text[end + len(END):]


def main():
    parser = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    parser.add_argument('--check', action='store_true',
                        help='exit with status 1 if the patterns are out of date')
    parser.add_argument('lex', help='lex.l')
    args = parser.parse_args()

    with open(args.lex, encoding='utf-8') as f:
        text = f.read()
    new = generate(text)
    if args.check:
        if new != text:
            sys.exit('%s: UTF-8 name patterns are out of date; run ninja utf8-names' % args.lex)
        return
    if new != text:
        with open(args.lex, 'w', encoding='utf-8') as f:
            f.write(new)


if __name__ == '__main__':
    main()
